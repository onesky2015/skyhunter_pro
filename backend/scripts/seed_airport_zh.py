def main():
    updated = 0
    skipped = 0

    with Session(engine) as session:
        for iata, (name_zh, muni_zh) in AIRPORT_ZH_MAP.items():
            airport = session.exec(
                select(Airport).where(Airport.iata_code == iata)
            ).first()

            if airport is None:
                print(f"  [SKIP] {iata} not in database")
                skipped += 1
                continue

            changed = False
            if airport.name_zh is None:
                airport.name_zh = name_zh
                changed = True
            if airport.municipality_zh is None:
                airport.municipality_zh = muni_zh
                changed = True

            if changed:
                session.add(airport)
                updated += 1
            else:
                skipped += 1

        session.commit()

    print(f"\n[DONE] updated={updated}, skipped={skipped}")


if __name__ == "__main__":
    main()
